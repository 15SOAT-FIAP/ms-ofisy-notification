"""Local event scenarios. No AWS credential chain or production endpoint is used."""
import argparse
import json
import time
import uuid
from datetime import datetime, timezone

import boto3
from botocore.config import Config

ENDPOINT = "http://localstack:4566"


def client(service):
    return boto3.client(service, endpoint_url=ENDPOINT, region_name="us-east-1",
                        aws_access_key_id="test", aws_secret_access_key="test",
                        config=Config(connect_timeout=3, read_timeout=5, retries={"max_attempts": 1}))


def event(kind):
    return {"eventId": str(uuid.uuid4()), "type": kind,
            "serviceOrderId": str(uuid.uuid4()) if kind == "QuoteCreated" else None,
            "occurredAt": datetime.now(timezone.utc).isoformat(),
            "payload": ({"quoteId": str(uuid.uuid4()), "totalPrice": "123.45"}
                        if kind == "QuoteCreated" else
                        {"stockId": str(uuid.uuid4()), "productName": "Radiador", "currentQuantity": 2, "minThreshold": 10})}


def send(body, topic=None):
    sns = client("sns")
    name = topic or ("ofisy-stock-events.fifo" if body["type"] == "StockLow" else "ofisy-billing-events.fifo")
    arn = next(t["TopicArn"] for t in sns.list_topics()["Topics"] if t["TopicArn"].endswith(":" + name))
    sns.publish(TopicArn=arn, Message=json.dumps(body),
                MessageGroupId=body.get("serviceOrderId") or body["payload"]["stockId"],
                MessageDeduplicationId=str(uuid.uuid4()))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("scenario", choices=["stock", "quote", "invalid", "status", "replay"])
    args = parser.parse_args()
    sqs = client("sqs")
    if args.scenario == "status":
        for name in ["ofisy-notification.fifo", "ofisy-notification-dlq.fifo"]:
            queue = sqs.get_queue_url(QueueName=name)["QueueUrl"]
            print(name, sqs.get_queue_attributes(QueueUrl=queue, AttributeNames=["ApproximateNumberOfMessages", "ApproximateNumberOfMessagesNotVisible"])["Attributes"])
    elif args.scenario == "replay":
        queue = sqs.get_queue_url(QueueName="ofisy-notification-dlq.fifo")["QueueUrl"]
        for message in sqs.receive_message(QueueUrl=queue, MaxNumberOfMessages=1, WaitTimeSeconds=1).get("Messages", []):
            body = json.loads(message["Body"])
            # Repair only the malformed scenario generated by this tool.
            if body["type"] == "StockLow" and "currentQuantity" not in body["payload"]:
                body["payload"]["currentQuantity"] = 2
            send(body)
            for _ in range(60):
                stored = client("dynamodb").get_item(TableName="Notifications", Key={"id": {"S": body["eventId"]}}, ConsistentRead=True)
                if "Item" in stored:
                    break
                time.sleep(1)
            else:
                raise RuntimeError("Replay not confirmed; message retained in DLQ")
            sqs.delete_message(QueueUrl=queue, ReceiptHandle=message["ReceiptHandle"])
            print(json.dumps(body))
    else:
        body = event("QuoteCreated" if args.scenario == "quote" else "StockLow")
        if args.scenario == "invalid":
            del body["payload"]["currentQuantity"]
        send(body)
        print(json.dumps(body))


if __name__ == "__main__":
    main()
